#!/usr/bin/env python3
"""Regenerates casa-source.md and casa-code.json from the files tracked in git.

Run from the repo root after committing changes:
    python3 scripts/export-source.py
Then upload casa-source.md to the Claude project files.
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUTS = {"casa-source.md", "casa-code.json"}
BINARY_EXT = {".png", ".jpg", ".jpeg", ".gif", ".ico", ".webp", ".woff", ".woff2"}
FENCE_LANG = {".js": "js", ".jsx": "jsx", ".ts": "ts", ".json": "json", ".jsonc": "jsonc",
              ".css": "css", ".html": "html", ".md": "md", ".py": "python"}

files = subprocess.run(["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()
files = [f for f in files if f not in OUTPUTS and Path(f).suffix.lower() not in BINARY_EXT]

contents = {f: (ROOT / f).read_text(encoding="utf-8") for f in files}

(ROOT / "casa-code.json").write_text(json.dumps(contents, ensure_ascii=False, indent=2), encoding="utf-8")

parts = ["# Casa source\n", "Generated by scripts/export-source.py. Each file is under a `FILE: <path>` heading.\n"]
for f, text in contents.items():
    lang = FENCE_LANG.get(Path(f).suffix.lower(), "")
    fence = "````" if "```" in text else "```"
    parts.append(f"\n## FILE: {f}\n\n{fence}{lang}\n{text.rstrip()}\n{fence}\n")
(ROOT / "casa-source.md").write_text("".join(parts), encoding="utf-8")

print(f"Exported {len(contents)} files")
